// Lightweight HTML mocks of the shared components, derived from the real code.
//
//   node shared/scripts/mocks.js build                 write <Name>.mock.html next to each component
//   node shared/scripts/mocks.js check                 fail if a mock is missing or stale
//   node shared/scripts/mocks.js bundle <prototype>    inline the CSS into one shareable file
//
// Each component has a <Name>.states.jsx listing the states worth showing, like a
// Storybook story: [{ name, render, variant?, component?, background? }]. `component`
// overrides the stamped name when a state renders a more specific component. Vite's SSR loads the real JSX and renders each state to static
// HTML, and the CSS the component actually imports goes in with it. Same code in,
// same HTML out, so re-running build produces no diff unless a component changed.
import fs from "fs";
import path from "path";
import { createServer } from "vite";
import { renderToStaticMarkup } from "react-dom/server";

const root = path.join(import.meta.dirname, "..", "..");
const frontend = path.join(root, "frontend");
const componentsDir = path.join(frontend, "src", "components");
const prototypesDir = path.join(root, "prototypes");

function findStatesFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return findStatesFiles(full);
    return entry.name.endsWith(".states.jsx") ? [full] : [];
  });
}

function findCss(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return findCss(full);
    return entry.name.endsWith(".css") ? [full] : [];
  });
}

// Every CSS file a module pulls in, following its imports. This is how a mock
// carries exactly the styles its component uses, and no others.
function cssFor(moduleGraph, file, seen = new Set()) {
  const mod = moduleGraph.getModuleById(file);
  if (!mod || seen.has(file)) return [];
  seen.add(file);
  return [...mod.importedModules].flatMap((dep) => {
    if (!dep.file) return [];
    if (dep.file.endsWith(".css")) return [dep.file];
    return cssFor(moduleGraph, dep.file, seen);
  });
}

// SVG imports render as dev-server URLs (in src="" or a CSS url()). Inline them
// as data URIs so the mock stands alone.
function inlineAssets(html) {
  return html.replace(/\/src\/([\w/.-]+\.svg)/g, (_, rel) => {
    const svg = fs.readFileSync(path.join(frontend, "src", rel));
    return `data:image/svg+xml;base64,${svg.toString("base64")}`;
  });
}

// Mark the component's root element with what it is. These attributes survive
// being copied into a prototype, so anything reading the prototype later (like
// design-on-canvas rebuilding it in Figma) knows exactly which component and
// variant each piece is, and can find its Figma node through Code Connect.
function stamp(html, component, state, variant) {
  const attrs = [`data-component="${component}"`, `data-state="${state}"`];
  if (variant) attrs.push(`data-variant="${variant}"`);
  return html.replace(/^<([a-zA-Z][\w-]*)/, `<$1 ${attrs.join(" ")}`);
}

const read = (file) => fs.readFileSync(file, "utf8").trim();
const rel = (file) => path.relative(root, file);

function page(title, css, body) {
  return `<!doctype html>
<!-- Generated by \`npm run mocks:build\` from the real component code. Do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<style>
${css}
.mock-state { padding: 16px; }
.mock-state > h2 { font: 600 12px/1.4 sans-serif; text-transform: uppercase; letter-spacing: .08em; color: #647573; margin: 0 0 8px; }
</style>
</head>
<body>
${body}
</body>
</html>
`;
}

async function renderAll() {
  const vite = await createServer({
    configFile: path.join(frontend, "vite.config.js"),
    server: { middlewareMode: true, hmr: false },
    appType: "custom",
    optimizeDeps: { disabled: true },
    logLevel: "silent",
  });
  const globalCss = read(path.join(frontend, "src", "styles.css"));
  const mocks = [];
  try {
    for (const statesFile of findStatesFiles(path.join(frontend, "src")).sort()) {
      const name = path.basename(statesFile, ".states.jsx");
      const { default: states } = await vite.ssrLoadModule(statesFile);
      const sections = states.map(({ name: state, component, variant, background, render }) => {
        const markup = stamp(inlineAssets(renderToStaticMarkup(render())), component ?? name, state, variant);
        const style = background ? ` style="background: ${background}"` : "";
        return `<section class="mock-state" data-state="${state}"${style}>\n<h2>${state}</h2>\n${markup}\n</section>`;
      });
      const css = [...new Set(cssFor(vite.moduleGraph, statesFile))].sort().map(read);
      mocks.push({
        file: path.join(path.dirname(statesFile), `${name}.mock.html`),
        html: page(`${name} (mock)`, [globalCss, ...css].join("\n\n"), sections.join("\n\n")),
      });
    }
  } finally {
    await vite.close();
  }

  // Every stylesheet in the app in one file, for composing prototypes.
  const allCss = findCss(path.join(frontend, "src")).sort()
    .filter((f) => !f.endsWith("styles.css")).map(read);
  mocks.push({
    file: path.join(prototypesDir, "shop.css"),
    html: `/* Generated by \`npm run mocks:build\`. Do not edit. */\n${[globalCss, ...allCss].join("\n\n")}\n`,
  });
  return mocks;
}

// Components that should have a mock: every directory in components/ with its own .jsx.
function missingStates() {
  return fs.readdirSync(componentsDir).filter((name) => {
    const dir = path.join(componentsDir, name);
    return fs.existsSync(path.join(dir, `${name}.jsx`)) && !fs.existsSync(path.join(dir, `${name}.states.jsx`));
  });
}

const [command, target] = process.argv.slice(2);

if (command === "build") {
  const mocks = await renderAll();
  for (const { file, html } of mocks) {
    const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (before === html) continue;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, html);
    console.log(`${before === null ? "created" : "updated"} ${rel(file)}`);
  }
  for (const name of missingStates()) console.log(`no states file: components/${name}`);
  console.log(`${mocks.length - 1} component mocks, plus prototypes/shop.css`);
} else if (command === "check") {
  const problems = (await renderAll())
    .filter(({ file, html }) => !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== html)
    .map(({ file }) => `stale or missing: ${rel(file)}`)
    .concat(missingStates().map((name) => `no states file: components/${name}`));
  if (problems.length) {
    console.error(`Mocks check failed (run \`npm run mocks:build\`):\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  console.log("Mocks check passed.");
} else if (command === "bundle") {
  if (!target) {
    console.error("Usage: npm run mocks:bundle -- <prototype-name>");
    process.exit(1);
  }
  const dir = path.join(prototypesDir, target);
  const source = fs.readFileSync(path.join(dir, "index.html"), "utf8");
  const bundled = source.replace(/<link rel="stylesheet" href="\.\.\/shop\.css">/,
    `<style>\n${read(path.join(prototypesDir, "shop.css"))}\n</style>`);
  const out = path.join(dir, `${target}.html`);
  fs.writeFileSync(out, bundled);
  console.log(`wrote ${rel(out)}, one file with everything inlined`);
} else {
  console.error("Usage: node shared/scripts/mocks.js build | check | bundle <prototype-name>");
  process.exit(1);
}
